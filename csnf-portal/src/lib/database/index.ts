import type { Database } from "./database.types";

// ============================================================
// EXPORTACIÓN PRINCIPAL
// ============================================================

export type { Database };

// ============================================================
// ESQUEMA PUBLIC
// ============================================================

export type PublicSchema =
  Database["public"];

// ============================================================
// TABLAS
// ============================================================

export type Tables =
  PublicSchema["Tables"];

export type TableNames =
  keyof Tables;

// ============================================================
// FILAS
// ============================================================

export type Row<
  T extends TableNames
> = Tables[T]["Row"];

// ============================================================
// INSERT
// ============================================================

export type Insert<
  T extends TableNames
> = Tables[T]["Insert"];

// ============================================================
// UPDATE
// ============================================================

export type Update<
  T extends TableNames
> = Tables[T]["Update"];

// ============================================================
// ENUMS
// ============================================================

export type Enums =
  PublicSchema["Enums"];

// ============================================================
// FUNCIONES
// ============================================================

export type Functions =
  PublicSchema["Functions"];

// ============================================================
// VISTAS
// ============================================================

export type Views =
  PublicSchema["Views"];